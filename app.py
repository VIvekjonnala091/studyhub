class DBConnection:
    def __init__(self, connection, postgres=False):
        self.connection = connection
        self.postgres = postgres

    def execute(self, query, params=None):
        if self.postgres:
            query = query.replace('?', '%s')
        return self.connection.execute(query, params or ())

    def executescript(self, script):
        return self.connection.executescript(script)

    def commit(self):
        return self.connection.commit()

    def close(self):
        return self.connection.close()


def db():
    """Use PostgreSQL when DATABASE_URL is configured; SQLite remains available locally."""
    if DATABASE_URL:
        if psycopg is None:
            raise RuntimeError('PostgreSQL is configured but psycopg is not installed.')
        return DBConnection(psycopg.connect(DATABASE_URL, row_factory=dict_row), postgres=True)
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    return DBConnection(con)


def init_db():
    con = db()
    if DATABASE_URL:
        con.execute('''
        CREATE TABLE IF NOT EXISTS materials (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          class_name TEXT NOT NULL,
          material_type TEXT NOT NULL,
          title TEXT NOT NULL,
          description TEXT DEFAULT '',
          filename TEXT NOT NULL,
          original_filename TEXT NOT NULL,
          created_at TEXT NOT NULL,
          storage_backend TEXT NOT NULL DEFAULT 'local',
          storage_path TEXT DEFAULT ''
        )
        ''')
        con.execute('''
        CREATE TABLE IF NOT EXISTS announcements (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          title TEXT NOT NULL,
          body TEXT NOT NULL,
          created_at TEXT NOT NULL
        )
        ''')
        con.commit()
        con.close()
        return

    con.executescript('''
    CREATE TABLE IF NOT EXISTS materials (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      class_name TEXT NOT NULL,
      material_type TEXT NOT NULL,
      title TEXT NOT NULL,
      description TEXT DEFAULT '',
      filename TEXT NOT NULL,
      original_filename TEXT NOT NULL,
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS announcements (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      title TEXT NOT NULL,
      body TEXT NOT NULL,
      created_at TEXT NOT NULL
    );
    ''')
    cols = {r['name'] for r in con.execute('PRAGMA table_info(materials)').fetchall()}
    if 'storage_backend' not in cols:
        con.execute("ALTER TABLE materials ADD COLUMN storage_backend TEXT NOT NULL DEFAULT 'local'")
    if 'storage_path' not in cols:
        con.execute("ALTER TABLE materials ADD COLUMN storage_path TEXT DEFAULT ''")
    con.commit()
    con.close()


init_db()


def admin_required(f):
    @wraps(f)
    def wrapped(*args, **kwargs):
        if not session.get('admin'):
            return redirect(url_for('admin_login', next=request.path))
        return f(*args, **kwargs)
    return wrapped


def allowed_file(name):
    return '.' in name and name.rsplit('.', 1)[1].lower() in ALLOWED


def now():
    return datetime.now().strftime('%Y-%m-%d %H:%M')


def supabase_headers(content_type=None):
    headers = {
        'apikey': SUPABASE_SERVICE_ROLE_KEY,
        'Authorization': f'Bearer {SUPABASE_SERVICE_ROLE_KEY}',
    }
    if content_type:
        headers['Content-Type'] = content_type
    return headers


def upload_to_supabase(file_storage, storage_path):
    url = f"{SUPABASE_URL}/storage/v1/object/{quote(SUPABASE_BUCKET, safe='')}/{quote(storage_path, safe='/')}"
    response = requests.post(url, headers=supabase_headers(file_storage.mimetype or 'application/octet-stream'), data=file_storage.stream, timeout=120)
    if response.status_code not in (200, 201):
        raise RuntimeError(f'Supabase upload failed ({response.status_code}): {response.text[:300]}')


def delete_from_supabase(storage_path):
    url = f"{SUPABASE_URL}/storage/v1/object/{quote(SUPABASE_BUCKET, safe='')}/{quote(storage_path, safe='/')}"
    response = requests.delete(url, headers=supabase_headers(), timeout=60)
    if response.status_code not in (200, 204):
        raise RuntimeError(f'Supabase delete failed ({response.status_code}): {response.text[:300]}')


def supabase_signed_url(storage_path):
    url = f"{SUPABASE_URL}/storage/v1/object/sign/{quote(SUPABASE_BUCKET, safe='')}/{quote(storage_path, safe='/')}"
    response = requests.post(url, headers=supabase_headers('application/json'), json={'expiresIn': SUPABASE_SIGNED_URL_SECONDS}, timeout=30)
    if response.status_code != 200:
        raise RuntimeError(f'Supabase signed URL failed ({response.status_code}): {response.text[:300]}')
    data = response.json()
    signed = data.get('signedURL') or data.get('signedUrl')
    if not signed:
        raise RuntimeError('Supabase did not return a signed URL.')
    return signed if signed.startswith('http') else f'{SUPABASE_URL}/storage/v1{signed}'


