@app.route('/admin/material/add', methods=['POST'])
@admin_required
def add_material():
    grade = request.form.get('grade'); typ = request.form.get('material_type'); title = request.form.get('title', '').strip(); desc = request.form.get('description', '').strip(); file = request.files.get('file')
    if grade not in ('9', '10') or typ not in MATERIAL_TYPES or not title or not file or not file.filename:
        flash('Please complete all material fields.', 'error'); return redirect(url_for('admin'))
    if not allowed_file(file.filename):
        flash('Unsupported file type.', 'error'); return redirect(url_for('admin'))
    original = secure_filename(file.filename)
    if not original:
        flash('Invalid filename.', 'error'); return redirect(url_for('admin'))
    stored = f'{uuid.uuid4().hex}_{original}'
    storage_path = f'class-{grade}/{typ.lower().replace(" ", "-")}/{stored}'
    backend = 'local'
    try:
        if CLOUD_STORAGE_ENABLED:
            upload_to_supabase(file, storage_path)
            backend = 'supabase'
            stored_for_db = stored
        else:
            file.save(UPLOADS / stored)
            stored_for_db = stored
    except Exception as exc:
        flash(f'Upload failed: {exc}', 'error'); return redirect(url_for('admin'))

    try:
        con = db()
        con.execute('''INSERT INTO materials(class_name,material_type,title,description,filename,original_filename,created_at,storage_backend,storage_path)
                       VALUES(?,?,?,?,?,?,?,?,?)''', (f'Class {grade}', typ, title, desc, stored_for_db, original, now(), backend, storage_path if backend == 'supabase' else ''))
        con.commit(); con.close()
    except Exception as exc:
        try:
            if backend == 'supabase':
                delete_from_supabase(storage_path)
            else:
                p = UPLOADS / stored
                if p.exists(): p.unlink()
        except Exception:
            pass
        flash(f'Material metadata could not be saved: {exc}', 'error')
        return redirect(url_for('admin'))
    flash('Material uploaded successfully.' + (' to cloud storage.' if backend == 'supabase' else ' locally (cloud storage is not configured).'), 'success')
    return redirect(url_for('admin'))


@app.route('/admin/material/delete/<int:item_id>', methods=['POST'])
@admin_required
def delete_material(item_id):
    con = db(); row = con.execute('SELECT * FROM materials WHERE id=?', (item_id,)).fetchone()
    if not row:
        con.close(); abort(404)
    try:
        if row['storage_backend'] == 'supabase' and row['storage_path']:
            delete_from_supabase(row['storage_path'])
        else:
            p = UPLOADS / row['filename']
            if p.exists(): p.unlink()
    except Exception as exc:
        con.close()
        flash(f'Could not delete the stored file, so the database record was kept: {exc}', 'error')
        return redirect(url_for('admin'))
    con.execute('DELETE FROM materials WHERE id=?', (item_id,)); con.commit(); con.close()
    flash('Material deleted.', 'success'); return redirect(url_for('admin'))


